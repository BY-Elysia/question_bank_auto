import fs from 'node:fs/promises';
import openapiTS, { astToString } from 'openapi-typescript';

const source = new URL('../contracts/openapi.json', import.meta.url);
const target = new URL('../src/contracts/api.d.ts', import.meta.url);
const header = '/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n';
const expected = header + astToString(await openapiTS(source));
const actual = await fs.readFile(target, 'utf8');
if (actual !== expected) {
  throw new Error('Generated API types are stale. Run npm run generate.');
}
console.log('Generated API types match OpenAPI.');
